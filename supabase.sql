-- Reality or Fake RP: shared history and settings
-- Run this entire script in Supabase > SQL Editor > New query.
create table if not exists public.draw_history (
  id bigint generated by default as identity primary key,
  item_name text not null check (char_length(item_name) between 1 and 100),
  result text not null check (result in ('แท้', 'ปลอม')),
  authenticity_rate integer not null check (authenticity_rate between 0 and 100),
  member_name text not null default 'ผู้เล่น' check (char_length(member_name) between 1 and 40),
  created_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  id integer primary key default 1 check (id = 1),
  authenticity_rate integer not null default 50 check (authenticity_rate between 0 and 100),
  updated_at timestamptz not null default now()
);

insert into public.app_settings (id, authenticity_rate)
values (1, 50) on conflict (id) do nothing;

alter table public.draw_history enable row level security;
alter table public.app_settings enable row level security;

-- Public read/insert for a simple community demo.
-- Anyone with the app URL can submit a draw or a display name.
-- For a private group or admin-only settings, add Supabase Auth and stricter policies.
drop policy if exists "Anyone can read draw history" on public.draw_history;
create policy "Anyone can read draw history" on public.draw_history
  for select to anon, authenticated using (true);

drop policy if exists "Anyone can add draw history" on public.draw_history;
create policy "Anyone can add draw history" on public.draw_history
  for insert to anon, authenticated with check (true);

drop policy if exists "Anyone can delete draw history" on public.draw_history;
create policy "Anyone can delete draw history" on public.draw_history
  for delete to anon, authenticated using (true);

drop policy if exists "Anyone can read app settings" on public.app_settings;
create policy "Anyone can read app settings" on public.app_settings
  for select to anon, authenticated using (true);

drop policy if exists "Anyone can update app settings" on public.app_settings;
create policy "Anyone can update app settings" on public.app_settings
  for update to anon, authenticated using (true) with check (true);

-- Enable realtime updates for shared draw history (safe to re-run if already added).
do $$
begin
  alter publication supabase_realtime add table public.draw_history;
exception
  when duplicate_object then null;
  when undefined_object then null;
end $$;